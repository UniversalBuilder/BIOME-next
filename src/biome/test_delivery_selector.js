const assert=require('node:assert/strict');
const {Selection}=require('./delivery_selector.js');
const image={file:'image',name:'image001.png',title:'Après filtrage',caption:'Résultat médian',kind:'image',group:'exchange',group_title:'Essai',bytes:200,revision:'a'};
const script={file:'script',name:'macro.ijm',title:'Macro',version:'v2',kind:'script',group:'work',bytes:10,revision:'b'};
const source={file:'mail',name:'source.msg',title:'Message source',kind:'source',group:'exchange',technical:true,bytes:1000,revision:'c'};
const state=new Selection([image,script,source]);
state.toggle('image',true);state.toggle('script',true);
assert.equal(state.visible('','image').length,1);
assert.equal(state.selected.size,2,'Filtering cannot clear hidden selection');
state.rename('script','Macro finale');
assert.equal(script.name,'macro.ijm');
assert.equal(state.visible('finale')[0].file,'script');
assert.equal(state.bytes(),210);
const payload=state.payload('Instructions');
assert.deepEqual(payload.files,['image','script']);
assert.deepEqual(payload.revisions,{image:'a',script:'b'});
assert.equal(payload.display_labels.script,'Macro finale');
assert(!payload.files.includes('mail'),'Sources are never implicitly selected');
state.references.external='reference';state.references.other='copy';
assert.deepEqual(state.payload('').dataset_ids,['external','other']);
assert.deepEqual(state.payload('').copy_dataset_ids,['other']);
state.toggle('image',false);assert.equal(state.selected.size,1);
state.chooseVisible(state.visible('','image').map(i=>i.file),true);
assert.equal(state.selected.size,2);
assert.throws(()=>state.rename('script','   '));
assert.throws(()=>state.rename('script','x'.repeat(201)));
console.log('Delivery selection: stable filters, labels, original names, sources and external-data modes OK.');
