def synthetic_png(path,mask=False):
    width=128;height=96;rows=[]
    for y in range(height):
        row=[]
        for x in range(width):
            inside=any((x-cx)**2+(y-cy)**2<radius**2 for cx,cy,radius in [(30,30,12),(87,29,16),(62,69,13)])
            row.append((255 if inside else 0) if mask else ((160+(x+y)%60) if inside else 12+(x*7+y*11)%15))
        rows.append(b'\0'+bytes(row))
    def chunk(kind,payload):return struct.pack('!I',len(payload))+kind+payload+struct.pack('!I',zlib.crc32(kind+payload)&0xffffffff)
    raw=b'\x89PNG\r\n\x1a\n'+chunk(b'IHDR',struct.pack('!IIBBBBB',width,height,8,0,0,0,0))+chunk(b'IDAT',zlib.compress(b''.join(rows)))+chunk(b'IEND',b'')
    path.write_bytes(raw)


def install_demo(parent):
    parent=existing_folder(parent);final=parent/'BIOME-Demo'
    if final.exists():raise ValueError('La démonstration existe déjà ici. Ouvrez son dossier Catalogue ou choisissez une autre destination.')
    stage=parent/('.installing-demo-'+uuid.uuid4().hex);stage.mkdir()
    create_catalogue(str(stage),'Catalogue',demo=True)
    catalogue=stage/'Catalogue';originals=stage/'Originals';originals.mkdir()
    synthetic_png(originals/'synthetic-cells.png');synthetic_png(originals/'synthetic-mask.png',True)
    (originals/'README.txt').write_text('SYNTHETIC DEMONSTRATION DATA\nThree artificial circular objects on a generated background.\nNo patient, researcher or experimental data. Pixel values and measurements are fictional.\nGenerated by BIOME; suitable for exercising the application, not validating scientific methods.\n',encoding='utf-8')
    anchor=catalogue/'.catalog-anchor';created=[]
    definitions=[
        ('Cell segmentation advice','Alex Example','Aster Demo Lab','consulting',15,
         'Could you recommend an approach for segmenting these synthetic cells?'),
        ('Fiji macro development','Morgan Example','Aster Demo Lab','development',45,
         'Build and document a small thresholding macro for synthetic images.'),
        ('Synthetic image analysis','Sam Example','Polar Demo Lab','analysis',90,
         'Provide example measurements and a labelled result for these artificial objects.'),
    ]
    for index,(title,contact,group,activity,minutes,request) in enumerate(definitions):
        item=store.create_project(anchor,{'title':'DEMO — '+title,'contact':contact,'group':group,
              'email':contact.split()[0].lower()+'@example.org','request':request,
              'originals_location':str(originals)})
        root=store.project_catalog(anchor)[item['key']];created.append(root)
        metadata=store.load(root/'biome.json');metadata['demo']=True;store.write_json(root/'biome.json',metadata)
        store.update_framing(root,{'status':'Review' if index==1 else 'Completed','objective':request,
              'deliverable':['Advice and an illustration','Macro v2 and instructions','Synthetic mask and measurements'][index],
              'next_step':'Explore this fictional example, then create your own catalogue.',
              'validation':'Demonstration only; no scientific validation is claimed.',
              'activity_type':activity,'software':['Fiji'],'modalities':[],'topics':['Segmentation']})
        assets=[{'name':'synthetic-cells.png','content':base64.b64encode((originals/'synthetic-cells.png').read_bytes()).decode(),
                 'caption':'Artificial image: three generated objects.','role':'attachment'}]
        if index==1:
            for version,code in [('v1','setAutoThreshold("Otsu dark");\nrun("Convert to Mask");\n'),('v2','run("Median...", "radius=1");\nsetAutoThreshold("Otsu dark");\nrun("Convert to Mask");\n')]:
                assets.append({'name':'segmentation_'+version+'.ijm','content':base64.b64encode(code.encode()).decode(),
                               'role':'version','label':version,'caption':version+' — demonstration macro; test on a copy.'})
        if index==2:
            assets.append({'name':'synthetic-mask.png','content':base64.b64encode((originals/'synthetic-mask.png').read_bytes()).decode(),'role':'attachment','caption':'Generated ground-truth mask; illustrative only.'})
            assets.append({'name':'measurements.csv','content':base64.b64encode(b'object_id,illustrative_area_px\n1,437\n2,793\n3,517\n').decode(),'role':'attachment','caption':'Fictional example measurements in pixels.'})
        store.add_entry(root,{'type':'experiment' if index else 'exchange','text':'FICTIONAL DEMONSTRATION\n\n'+[
            'A brief advice session. The image is synthetic. Keep the original data folder separate and retain the final advice in the notebook.',
            'Version 1 applies a threshold; version 2 adds a median filter. Compare the captions and prepare a delivery snapshot.',
            'Example outputs: generated mask and illustrative measurements. Results are not an interpretation of a biological experiment.'
            ][index],'date':'2026-01-12','time':f'{9+index:02d}:00','minutes':minutes,'tags':'demo, synthetic','attachments':assets})
        if index:
            store.make_delivery(root,{'files':[item['file'] for item in store.delivery_files(root) if item['file'].startswith('files/')],
                               'dataset_ids':[],'copy_dataset_ids':[],'note':'Fictional demonstration delivery. Original data remain separate.'})
    # Publish references to the final sibling Originals folder, never the staging path.
    for root in created:
        datasets=store.load(root/'records/datasets.json')
        for item in datasets:item['location']=str(final/'Originals')
        store.write_json(root/'records/datasets.json',datasets);write_companion(root,datasets)
    report=diagnose_catalog(catalogue)
    if report['errors']:raise ValueError('Démonstration non valide ; aucun catalogue actif modifié.')
    (stage/'README.txt').write_text('BIOME DEMO\n\nOpen Catalogue in BIOME. Originals contains generated example images, separate from the documentary catalogue.\nAll names, requests and recorded times are fictional. This is not an example of scientific validation.\nThe installer never replaces an existing demo. Remove or retain this separate folder as you prefer.\n',encoding='utf-8')
    publish_directory(stage,final)
    return {**catalogue_info(final/'Catalogue'),'data_location':str(final/'Originals'),'installed':True}
